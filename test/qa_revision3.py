from pathlib import Path
from playwright.sync_api import sync_playwright
ROOT=Path(__file__).resolve().parents[1]
roothtml=(ROOT/'dist/index.html').read_text(encoding='utf-8')
shots=ROOT/'preview'; shots.mkdir(exist_ok=True)
errors=[]
with sync_playwright() as p:
 b=p.chromium.launch(executable_path='/usr/bin/chromium', headless=True, args=['--no-sandbox'])
 ctx=b.new_context(viewport={'width':390,'height':844}, device_scale_factor=1)
 page=ctx.new_page();page.on('pageerror',lambda exc: errors.append(str(exc)))
 page.route('https://**', lambda route: route.abort());page.set_content(roothtml,wait_until='domcontentloaded');page.wait_for_timeout(500)
 print('HOME title:',page.locator('.welcome h1').inner_text())
 print('HOME has retired refund section?',page.locator('#h-refund').count())
