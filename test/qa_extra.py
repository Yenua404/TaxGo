from pathlib import Path
from playwright.sync_api import sync_playwright
root=Path(__file__).resolve().parents[1]
html=(root/'dist/index.html').read_text()
with sync_playwright() as p:
 b=p.chromium.launch(executable_path='/usr/bin/chromium',headless=True,args=['--no-sandbox'])
 ctx=b.new_context(viewport={'width':390,'height':844},device_scale_factor=1)
 page=ctx.new_page();page.set_content(html, wait_until='domcontentloaded')
 print('NATIVE BARCODE DETECTOR',page.evaluate('typeof window.BarcodeDetector'))
 page.locator('[data-arg="calendar"].tab').click()
 page.locator('.reminder-section').scroll_into_view_if_needed()
 page.screenshot(path=str(root/'preview'/'reminders-light.png'))
 print('CAL EN LABELS TEST')
 page.locator('[data-act=language][data-arg=en]').click()
 page.locator('.reminder-section').scroll_into_view_if_needed()
 page.screenshot(path=str(root/'preview'/'reminders-en.png'))
 print(page.locator('.reminder-section').inner_text()[:1050])
 page.locator('[data-act=theme]').click()
 page.locator('.reminder-section').scroll_into_view_if_needed()
 page.screenshot(path=str(root/'preview'/'reminders-en-dark.png'))
 page.locator('.tabs [data-arg=departure]').click()
 page.locator('[data-act=showChecklist]').first.click()
 print('CHECKLIST EN:',page.locator('#checklist-content').inner_text()[:850])
 print('MODAL:',page.locator('#dlg-checklist .btn-sign').last.inner_text())
 page.locator('#dlg-checklist [data-act=close]').first.click()
 page.locator('.tabs [data-arg=home]').click()
 page.screenshot(path=str(root/'preview'/'home-en-dark.png'))
 print('HOME EN:',page.locator('.welcome').inner_text()[:250])
 b.close()
