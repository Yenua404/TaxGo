 page.screenshot(path=str(shots/'home-light.png'))
 page.locator('[data-key=refund-receipts]').click();print('RECEIPTS:',page.locator('.page-title').first.inner_text())
 page.screenshot(path=str(shots/'receipts-light.png'))
 page.locator('.tabs [data-arg=departure]').click();print('DEPARTURE first section:',page.locator('#view > *').first.inner_text()[:100]);print('CHECKLIST inline?',page.locator('#view .checklist-groups').count())
 page.screenshot(path=str(shots/'departure-light.png'))
 page.locator('[data-act=showChecklist]').first.click();print('CHECKLIST modal?',page.locator('#dlg-checklist').evaluate('(e)=>e.open'))
 page.screenshot(path=str(shots/'departure-popup.png'))
 page.locator('#chk-0').check();print('check selected?',page.locator('#chk-0').is_checked())
