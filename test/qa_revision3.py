 page.screenshot(path=str(shots/'calendar-light.png'))
 page.locator('[data-key=rem-edit-eve]').click();print('reminder dialog open?',page.locator('#dlg-reminder').evaluate('(e)=>e.open'))
 page.locator('#rem-mode').select_option('monthly');page.locator('#rem-date').fill('2026-11-29');page.locator('#form-reminder button[type=submit]').click();print('reminder mode',page.locator('.reminder-card').first.locator('.reminder-mode').inner_text())
 page.locator('#rem-global').uncheck();print('global now',page.locator('#rem-global').is_checked(),'event marks',page.locator('.mk-remind').count())
 page.screenshot(path=str(shots/'calendar-custom-off.png'))
 page.locator('#rem-global').check()
 page.locator('.tabs [data-arg=wallet]').click();print('QR upload UI?',page.locator('.qr-upload-button').count())
 page.screenshot(path=str(shots/'wallet-light.png'))
 # Mock real browser barcode detection for a deterministic upload-path test.
 page.evaluate("() => { window.BarcodeDetector = class { constructor() {} async detect(canvas) {return [{rawValue: 'https://example.org/qr-demo'}]} } }")
 from PIL import Image,ImageDraw
 img=Image.new('RGB',(320,320),'white'); d=ImageDraw.Draw(img); d.rectangle((35,35,285,285),outline='black',width=15)
 testimg=shots/'mock-qr.png';img.save(testimg)
 page.locator('#qr-image-input').set_input_files(str(testimg))
 page.wait_for_timeout(700)
 print('QR has image',page.locator('.qr-saved img').count(),'payload?',page.locator('.qr-payload code').inner_text() if page.locator('.qr-payload code').count() else '')
 page.screenshot(path=str(shots/'wallet-qr-saved.png'))
 print('QR stored in current UI',page.locator('.qr-saved img').count())
 page.locator('[data-act=qrRemove]').click();print('QR removed',page.locator('.qr-upload-button').count())
 page.locator('.tabs [data-arg=departure]').click();page.locator('[data-act=language][data-arg=ja]').click()
 page.screenshot(path=str(shots/'departure-ja.png'))
 print('JP view?',page.locator('html').get_attribute('lang'),'contains original Korean desc?', '공항 도착 목표' in page.locator('#view').inner_text())
 page.locator('[data-act=showChecklist]').first.click();print('JP checklist text',page.locator('#checklist-content .step-name').first.inner_text())
 page.locator('#dlg-checklist').evaluate('(el)=>el.close()')
 page.locator('[data-act=language][data-arg=en]').click()
 page.screenshot(path=str(shots/'departure-en.png'))
 print('EN airport?',page.locator('#view').inner_text()[:125])
 page.locator('[data-act=theme]').click()
 page.screenshot(path=str(shots/'departure-dark.png'))
 print('DARK?',page.locator('html').get_attribute('data-theme'))
